#!/usr/bin/env python3
"""Write web/lib/a9table.js from motreader/_a9_table.py (the A9 / S9000e
button function templates), so the web app uses the same table as the CLI.

    python3 tools/build_a9_table_js.py           # rewrite the file
    python3 tools/build_a9_table_js.py --check   # exit 1 if it is stale
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from motreader._a9_table import FUNCTIONS, ALLOWED  # noqa: E402

OUT = os.path.join(ROOT, "web", "lib", "a9table.js")


def render() -> str:
    j = json.dumps
    lines = [
        "// @ts-check",
        "/**",
        " * GENERATED by tools/build_a9_table_js.py from motreader/_a9_table.py; do not",
        " * edit by hand. The A9 / S9000e button function templates (see buttons.js).",
        " *",
        " * label -> [full name, copy-1 record, copy-2 record, indicator entries, data slots]",
        " *   record: [6-byte template hex, flags, code]; code null = the key's home code,",
        " *   \"+1d\" = home + 0x1d, a number = fixed code. Indicator entries: hex",
        " *   \"ggffppFFxx\" (the key's LED is added to FF). Data slots: [where, byte],",
        " *   where \"r1\" / \"r2\" (records) or \"s<n>\" (indicator entry n).",
        " */",
        "",
        "/** @typedef {[string, number, number | string | null]} A9Record */",
        "/** @typedef {[string, A9Record, A9Record, string[], [string, number][]]} A9Function */",
        "",
        "/** @type {Readonly<Record<string, A9Function>>} */",
        "export const FUNCTIONS = Object.freeze({",
    ]
    for lab, (name, r1, r2, sides, slots) in FUNCTIONS.items():
        lines.append(f"    {j(lab)}: [{j(name)}, {j(list(r1))}, {j(list(r2))}, "
                     f"{j(sides)}, {j([list(s) for s in slots])}],")
    lines += [
        "});",
        "",
        "/** The functions RSS offers per key class (\"ind\", \"keypad\", or a labelled key's name). */",
        "/** @type {Readonly<Record<string, readonly string[]>>} */",
        "export const ALLOWED = Object.freeze({",
    ]
    for k, labs in ALLOWED.items():
        lines.append(f"    {j(k)}: {j(labs)},")
    lines += ["});", ""]
    return "\n".join(lines)


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        with open(OUT) as fh:
            sys.exit(0 if fh.read() == text else 1)
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
